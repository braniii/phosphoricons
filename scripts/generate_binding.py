#!/usr/bin/env python3
"""Generate all LaTeX binding artefacts for the phosphoricons package.

Reads an unpacked @phosphor-icons/web npm tarball and emits into the shipped
package tree (phosphoricons/):

  truetype/Phosphor-<Weight>.ttf     renamed upstream fonts
  enc/phosphoricons<k>.enc           encodings over the 1512 base codepoints,
                                     shared by the five plain weights (6 chunks)
  enc/phosphoriconsduo<k>.enc        encodings over base + duotone-secondary
                                     codepoints, duotone weight only (12 chunks)
  tfm/ppicons<k><weight>.tfm         plain weights, via otftotfm
  tfm/ppiconsduo<k>.tfm              duotone weight
  map/phosphoricons.map              one line per tfm (direct TTF embedding)
  tex/uphosphoricons<k>.fd           U families, plain weights as NFSS series
  tex/uphosphoriconsduo<k>.fd        U families for the duotone weight
  tex/tuphosphoricons.fd             TU family for XeLaTeX/LuaLaTeX
  tex/phosphoricons-mapping.def      one \\__phosphoricons_def_icon:nnnnnn line
                                     per icon name (aliases included)

Glyphs are packed densely by sorted codepoint, so chunk/slot are positional
and differ between the two layouts; the mapping file stores both.

Note: the plain-weight encodings must never include the stray zero-advance
uniEE83 glyph the plain fonts carry — otftotfm (lcdf-typetools 2.108) crashes
on it. Base-codepoint-only encodings avoid it naturally.

Usage: generate_binding.py [--upstream build/upstream/package] [--out phosphoricons]

Requires: fontTools (pip), otftotfm (lcdf-typetools, ships with TeX Live).
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

from fontTools.ttLib import TTFont

WEIGHTS = ["thin", "light", "regular", "bold", "fill", "duotone"]
PLAIN_WEIGHTS = ["thin", "light", "regular", "bold", "fill"]
FAMILY = "phosphoricons"   # NFSS family stem and enc/fd/map basename
TFM_STEM = "ppicons"       # tfm basename stem (short to keep map/log lines sane)
CHUNK = 256

HEADER = """% Copyright 2026 Daniel Nagel
%
% This work may be distributed and/or modified under the
% conditions of the LaTeX Project Public License, either version 1.3c
% of this license or (at your option) any later version.
% The latest version of this license is in
%   http://www.latex-project.org/lppl.txt
% and version 1.3 or later is part of all distributions of LaTeX
% version 2005/12/01 or later.
%
% This work has the LPPL maintenance status `maintained'.
%
% The Current Maintainer of this work is Daniel Nagel
%
% This file was auto-generated by scripts/generate_binding.py
% from @phosphor-icons/web {version}. DO NOT EDIT.
%
"""


def upstream_font(upstream: Path, weight: str) -> Path:
    name = "Phosphor.ttf" if weight == "regular" else f"Phosphor-{weight.capitalize()}.ttf"
    return upstream / "src" / weight / name


def parse_css(upstream: Path):
    """Return (name -> base cp) from regular CSS and (cp -> secondary cp) from
    duotone CSS; verify the plain weights agree with regular."""
    def rules(weight, pseudo):
        css = (upstream / "src" / weight / "style.css").read_text()
        prefix = r"\.ph" if weight == "regular" else rf"\.ph-{weight}"
        pat = rf"{prefix}\.ph-([a-z0-9-]+):{pseudo}\s*\{{\s*content:\s*\"\\([0-9a-f]+)\""
        return {n: int(h, 16) for n, h in re.findall(pat, css)}

    base = rules("regular", "before")
    if not base:
        sys.exit("error: no icon rules parsed from regular/style.css")
    for w in PLAIN_WEIGHTS:
        if rules(w, "before") != base:
            sys.exit(f"error: {w}/style.css name->codepoint map differs from regular")

    duo_before = rules("duotone", "before")
    duo_after = rules("duotone", "after")
    for n, cp in duo_before.items():
        if base.get(n) != cp:
            sys.exit(f"error: duotone :before codepoint mismatch for '{n}'")
    secondary = {}
    for n, cp2 in duo_after.items():
        cp = duo_before.get(n)
        if cp is None:
            sys.exit(f"error: duotone :after without :before for '{n}'")
        if secondary.setdefault(cp, cp2) != cp2:
            sys.exit(f"error: conflicting secondary codepoints for U+{cp:04X}")
    # A few icons (e.g. cell-signal-none) have a single-layer duotone form:
    # only a :before rule, no :after. Those render as just the base glyph.
    missing = {cp for cp in base.values() if cp not in secondary}
    if missing:
        names = sorted(n for n, cp in base.items() if cp in missing)
        print(f"note: {len(missing)} icons have single-layer duotone: {', '.join(names)}")
    if len(missing) > 20:
        sys.exit("error: implausibly many icons lack a duotone secondary layer")
    return base, secondary


def pascal(name: str) -> str:
    macro = "".join(part.capitalize() for part in name.split("-"))
    if not re.fullmatch(r"[A-Za-z]+", macro):
        sys.exit(f"error: icon name '{name}' does not camelize to a pure-letter "
                 f"macro name ('{macro}'); generator needs updating")
    return macro


def ps_name(ttf: Path) -> str:
    font = TTFont(ttf)
    name = font["name"].getDebugName(6)
    if not name:
        sys.exit(f"error: no PostScript name in {ttf}")
    return name


def check_advances(out: Path, layouts: dict):
    """Warn about zero-advance glyphs that would end up in an encoding — they
    have crashed otftotfm before (see module docstring)."""
    for w in WEIGHTS:
        ttf = out / "truetype" / f"Phosphor-{w.capitalize()}.ttf"
        font = TTFont(ttf)
        cmap, hmtx = font.getBestCmap(), font["hmtx"]
        cps = layouts["duo" if w == "duotone" else "plain"][0]
        bad = [cp for cp in cps
               if cp in cmap and hmtx[cmap[cp]][0] == 0]
        if bad:
            print(f"warning: {w}: zero-advance glyphs in encoding: "
                  + ", ".join(f"U+{c:04X}" for c in bad[:10]))


def write_encs(out: Path, stem: str, cps: list[int]) -> int:
    (out / "enc").mkdir(parents=True, exist_ok=True)
    nchunks = -(-len(cps) // CHUNK)
    for k in range(nchunks):
        chunk = cps[k * CHUNK:(k + 1) * CHUNK]
        entries = [f"/uni{cp:04X}" for cp in chunk]
        entries += ["/.notdef"] * (CHUNK - len(chunk))
        body = f"/{stem}{k}[\n" + "\n".join(entries) + "\n] def\n"
        (out / "enc" / f"{stem}{k}.enc").write_text(
            f"% Generated by generate_binding.py. DO NOT EDIT.\n{body}")
    return nchunks


def tfm_jobs(nplain: int, nduo: int):
    """Yield (tfm-name, enc-stem, chunk, weight) for every tfm to build."""
    for w in PLAIN_WEIGHTS:
        for k in range(nplain):
            yield f"{TFM_STEM}{k}{w}", FAMILY, k, w
    for k in range(nduo):
        yield f"{TFM_STEM}duo{k}", f"{FAMILY}duo", k, "duotone"


def run_otftotfm(out: Path, nplain: int, nduo: int):
    tfm_dir = out / "tfm"
    if tfm_dir.exists():
        shutil.rmtree(tfm_dir)
    tfm_dir.mkdir(parents=True)
    for tfm, stem, k, w in tfm_jobs(nplain, nduo):
        cmd = ["otftotfm", "--literal-encoding", str(out / "enc" / f"{stem}{k}.enc"),
               "--name", tfm, "--tfm-directory", str(tfm_dir),
               "--no-updmap", "--no-map", "--force",
               str(out / "truetype" / f"Phosphor-{w.capitalize()}.ttf")]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            sys.exit(f"error: otftotfm failed for {tfm} (exit {res.returncode}):\n"
                     f"{res.stderr}")


def write_map(out: Path, nplain: int, nduo: int):
    (out / "map").mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by generate_binding.py. DO NOT EDIT."]
    for tfm, stem, k, w in tfm_jobs(nplain, nduo):
        ttf = out / "truetype" / f"Phosphor-{w.capitalize()}.ttf"
        lines.append(f"{tfm} {ps_name(ttf)} \"{stem}{k} ReEncodeFont\" "
                     f"<[{stem}{k}.enc <{ttf.name}")
    (out / "map" / f"{FAMILY}.map").write_text("\n".join(lines) + "\n")


def write_fds(out: Path, nplain: int, nduo: int, version: str):
    tex = out / "tex"
    tex.mkdir(parents=True, exist_ok=True)

    def fd(fam, shapes, subs):
        parts = [HEADER.format(version=version), f"\\DeclareFontFamily{{U}}{{{fam}}}{{}}\n"]
        for series, tfm in shapes:
            parts.append(f"\\DeclareFontShape{{U}}{{{fam}}}{{{series}}}{{n}}\n"
                         f"    {{<-> {tfm}}}{{}}\n")
        for series, target in subs:
            parts.append(f"\\DeclareFontShape{{U}}{{{fam}}}{{{series}}}{{n}}\n"
                         f"    {{<->ssub * {fam}/{target}/n}}{{}}\n")
        (tex / f"u{fam}.fd").write_text("".join(parts))

    for k in range(nplain):
        fd(f"{FAMILY}{k}",
           [(w, f"{TFM_STEM}{k}{w}") for w in PLAIN_WEIGHTS],
           [("m", "regular"), ("b", "bold"), ("bx", "bold")])
    for k in range(nduo):
        fd(f"{FAMILY}duo{k}",
           [("duotone", f"{TFM_STEM}duo{k}")],
           [("m", "duotone"), ("b", "duotone"), ("bx", "duotone")])

    parts = [HEADER.format(version=version), f"\\DeclareFontFamily{{TU}}{{{FAMILY}}}{{}}\n"]
    for w in WEIGHTS:
        parts.append(f"\\DeclareFontShape{{TU}}{{{FAMILY}}}{{{w}}}{{n}}\n"
                     f"    {{<-> \\UnicodeFontFile{{Phosphor-{w.capitalize()}.ttf}}{{}}}}{{}}\n")
    for series, target in [("m", "regular"), ("b", "bold"), ("bx", "bold")]:
        parts.append(f"\\DeclareFontShape{{TU}}{{{FAMILY}}}{{{series}}}{{n}}\n"
                     f"    {{<->ssub * {FAMILY}/{target}/n}}{{}}\n")
    (tex / f"tu{FAMILY}.fd").write_text("".join(parts))


def write_mapping(out: Path, base: dict, secondary: dict,
                  plain_slot: dict, duo_slot: dict, version: str):
    lines = [HEADER.format(version=version),
             "% \\__phosphoricons_def_icon:nnnnnn {macro} {name} {cp}",
             "%   {{plain-chunk}{plain-slot}} {{duo-chunk}{duo-slot}}",
             "%   {{cp2}{duo-chunk2}{duo-slot2}}   (empty for single-layer duotone)"]
    for name in sorted(base):
        cp = base[name]
        pc, ps = plain_slot[cp]
        dc, ds = duo_slot[cp]
        cp2 = secondary.get(cp)
        if cp2 is None:
            duo2 = ""
        else:
            dc2, ds2 = duo_slot[cp2]
            duo2 = f"{{\"{cp2:04X}}}{{{dc2}}}{{{ds2}}}"
        lines.append(f"\\__phosphoricons_def_icon:nnnnnn{{\\pp{pascal(name)}}}{{{name}}}"
                     f"{{\"{cp:04X}}}{{{{{pc}}}{{{ps}}}}}{{{{{dc}}}{{{ds}}}}}{{{duo2}}}")
    (out / "tex" / f"{FAMILY}-mapping.def").write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    root = Path(__file__).resolve().parent.parent
    ap.add_argument("--upstream", type=Path, default=root / "build/upstream/package")
    ap.add_argument("--out", type=Path, default=root / "phosphoricons")
    args = ap.parse_args()
    upstream, out = args.upstream, args.out
    if not upstream.is_dir():
        sys.exit(f"error: upstream not found at {upstream} — run scripts/fetch_upstream.sh")
    version = json.loads((upstream / "package.json").read_text())["version"]

    base, secondary = parse_css(upstream)
    macros = {pascal(n) for n in base}
    if len(macros) != len(base):
        sys.exit("error: camelized macro names collide")

    (out / "truetype").mkdir(parents=True, exist_ok=True)
    for w in WEIGHTS:
        shutil.copyfile(upstream_font(upstream, w),
                        out / "truetype" / f"Phosphor-{w.capitalize()}.ttf")

    plain_cps = sorted(set(base.values()))
    duo_cps = sorted(set(base.values()) | set(secondary.values()))
    plain_slot = {cp: (i // CHUNK, i % CHUNK) for i, cp in enumerate(plain_cps)}
    duo_slot = {cp: (i // CHUNK, i % CHUNK) for i, cp in enumerate(duo_cps)}
    layouts = {"plain": (plain_cps, plain_slot), "duo": (duo_cps, duo_slot)}
    check_advances(out, layouts)

    nplain = write_encs(out, FAMILY, plain_cps)
    nduo = write_encs(out, f"{FAMILY}duo", duo_cps)
    run_otftotfm(out, nplain, nduo)
    write_map(out, nplain, nduo)
    write_fds(out, nplain, nduo, version)
    write_mapping(out, base, secondary, plain_slot, duo_slot, version)

    print(f"@phosphor-icons/web {version}: {len(base)} icon names, "
          f"{len(plain_cps)} icons, {len(duo_cps)} duotone-layout glyphs")
    print(f"generated: {nplain}+{nduo} enc, {nplain * len(PLAIN_WEIGHTS) + nduo} tfm, "
          f"{nplain + nduo + 1} fd, 1 map, 1 mapping.def -> {out}")


if __name__ == "__main__":
    main()
